PROMPT [3/14] Table 1: USERS
CREATE TABLE USERS (
    USER_ID NUMBER PRIMARY KEY,
    USERNAME VARCHAR2(100) UNIQUE NOT NULL,
    EMAIL VARCHAR2(150) UNIQUE NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(50) DEFAULT 'SOC_ANALYST',
    FULL_NAME VARCHAR2(150),
    LAST_LOGIN TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

PROMPT [4/14] Table 2: ASSETS (Digital Twin Nodes)
CREATE TABLE ASSETS (
    ASSET_ID VARCHAR2(50) PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    DEVICE_TYPE VARCHAR2(50) NOT NULL,
    IP_ADDRESS VARCHAR2(45) NOT NULL,
    OPERATING_SYSTEM VARCHAR2(100),
    ZONE VARCHAR2(50) DEFAULT 'INTERNAL',
    CRITICALITY VARCHAR2(20) DEFAULT 'MEDIUM',
    SECURITY_STATE VARCHAR2(30) DEFAULT 'SECURE',
    OPEN_PORTS VARCHAR2(255),
    VULNERABILITY_COUNT NUMBER DEFAULT 0,
    RISK_SCORE NUMBER(5,2) DEFAULT 0.0,
    POSITION_X NUMBER DEFAULT 0,
    POSITION_Y NUMBER DEFAULT 0,
    LAST_UPDATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

PROMPT [5/14] Table 3: ASSET_CONNECTIONS (Digital Twin Links)
CREATE TABLE ASSET_CONNECTIONS (
    CONNECTION_ID NUMBER PRIMARY KEY,
    SOURCE_ASSET_ID VARCHAR2(50) NOT NULL REFERENCES ASSETS(ASSET_ID),
    TARGET_ASSET_ID VARCHAR2(50) NOT NULL REFERENCES ASSETS(ASSET_ID),
    PROTOCOL VARCHAR2(30) DEFAULT 'TCP',
    PORT NUMBER,
    BANDWIDTH_MBPS NUMBER DEFAULT 1000,
    IS_ENCRYPTED VARCHAR2(1) DEFAULT 'Y',
    IS_EXPOSED VARCHAR2(1) DEFAULT 'N',
    STATUS VARCHAR2(30) DEFAULT 'ACTIVE'
);

PROMPT [6/14] Table 4: VULNERABILITIES (CVE Catalog)
CREATE TABLE VULNERABILITIES (
    VULN_ID VARCHAR2(50) PRIMARY KEY,
    NAME VARCHAR2(150) NOT NULL,
    CVSS_SCORE NUMBER(3,1) NOT NULL,
    SEVERITY VARCHAR2(20) NOT NULL,
    DESCRIPTION VARCHAR2(1000),
    REMEDIATION VARCHAR2(1000),
    EXPLOITABILITY VARCHAR2(30) DEFAULT 'FUNCTIONAL',
    IS_ZERO_DAY VARCHAR2(1) DEFAULT 'N'
);

PROMPT [7/14] Table 5: ASSET_VULNERABILITIES (Asset-CVE Cross Reference)
CREATE TABLE ASSET_VULNERABILITIES (
    ID NUMBER PRIMARY KEY,
    ASSET_ID VARCHAR2(50) NOT NULL REFERENCES ASSETS(ASSET_ID),
    VULN_ID VARCHAR2(50) NOT NULL REFERENCES VULNERABILITIES(VULN_ID),
    EXPOSED_PORT NUMBER,
    STATUS VARCHAR2(30) DEFAULT 'UNPATCHED',
    DISCOVERED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

PROMPT [8/14] Table 6: SECURITY_CONTROLS
CREATE TABLE SECURITY_CONTROLS (
    CONTROL_ID VARCHAR2(50) PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    CONTROL_TYPE VARCHAR2(50) NOT NULL,
    APPLIED_TO_ASSET VARCHAR2(50) REFERENCES ASSETS(ASSET_ID),
    STATUS VARCHAR2(30) DEFAULT 'ACTIVE',
    EFFECTIVENESS_PCT NUMBER(5,2) DEFAULT 80.0,
    DESCRIPTION VARCHAR2(500)
);

PROMPT [9/14] Table 7: ATTACK_TECHNIQUES (MITRE ATT&CK Matrix)
CREATE TABLE ATTACK_TECHNIQUES (
    TECHNIQUE_ID VARCHAR2(30) PRIMARY KEY,
    NAME VARCHAR2(150) NOT NULL,
    TACTIC VARCHAR2(50) NOT NULL,
    DESCRIPTION VARCHAR2(1000),
    SEVERITY_WEIGHT NUMBER(4,2) DEFAULT 1.0
);

PROMPT [10/14] Table 8: ATTACK_PATHS (Predicted Trajectories)
CREATE TABLE ATTACK_PATHS (
    PATH_ID VARCHAR2(50) PRIMARY KEY,
    NAME VARCHAR2(150) NOT NULL,
    ENTRY_POINT VARCHAR2(50) NOT NULL REFERENCES ASSETS(ASSET_ID),
    TARGET_ASSET VARCHAR2(50) NOT NULL REFERENCES ASSETS(ASSET_ID),
    HOP_COUNT NUMBER NOT NULL,
    RISK_SCORE NUMBER(5,2) NOT NULL,
    CONFIDENCE_SCORE NUMBER(5,2) NOT NULL,
    VULNERABILITY_COUNT NUMBER NOT NULL,
    CRITICAL_ASSETS_AFFECTED NUMBER NOT NULL,
    PRIORITY VARCHAR2(20) NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'ACTIVE',
    EXPLANATION VARCHAR2(4000)
);

PROMPT [11/14] Table 9: ATTACK_PATH_STEPS
CREATE TABLE ATTACK_PATH_STEPS (
    STEP_ID NUMBER PRIMARY KEY,
    PATH_ID VARCHAR2(50) NOT NULL REFERENCES ATTACK_PATHS(PATH_ID),
    STEP_ORDER NUMBER NOT NULL,
    FROM_ASSET VARCHAR2(50) NOT NULL REFERENCES ASSETS(ASSET_ID),
    TO_ASSET VARCHAR2(50) NOT NULL REFERENCES ASSETS(ASSET_ID),
    TECHNIQUE_ID VARCHAR2(30) REFERENCES ATTACK_TECHNIQUES(TECHNIQUE_ID),
    VULN_ID VARCHAR2(50) REFERENCES VULNERABILITIES(VULN_ID),
    STEP_RISK NUMBER(5,2) NOT NULL,
    DESCRIPTION VARCHAR2(500)
);

PROMPT [12/14] Table 10: RISK_ASSESSMENTS
CREATE TABLE RISK_ASSESSMENTS (
    ASSESSMENT_ID NUMBER PRIMARY KEY,
    OVERALL_SECURITY_SCORE NUMBER(5,2) NOT NULL,
    NETWORK_RISK_SCORE NUMBER(5,2) NOT NULL,
    VULNERABILITY_HEALTH NUMBER(5,2) NOT NULL,
    NETWORK_SEGMENTATION NUMBER(5,2) NOT NULL,
    ASSET_EXPOSURE NUMBER(5,2) NOT NULL,
    ATTACK_PATH_RISK NUMBER(5,2) NOT NULL,
    SECURITY_CONTROLS_SCORE NUMBER(5,2) NOT NULL,
    ASSESSED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

PROMPT [13/14] Table 11: DEFENSE_RECOMMENDATIONS
CREATE TABLE DEFENSE_RECOMMENDATIONS (
    REC_ID VARCHAR2(50) PRIMARY KEY,
    TITLE VARCHAR2(200) NOT NULL,
    AFFECTED_ASSET_ID VARCHAR2(50) REFERENCES ASSETS(ASSET_ID),
    ACTION_TYPE VARCHAR2(50) NOT NULL,
    REASON VARCHAR2(1000) NOT NULL,
    ESTIMATED_RISK_REDUCTION NUMBER(5,2) NOT NULL,
    PRIORITY VARCHAR2(20) NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'PENDING',
    APPLIED_AT TIMESTAMP
);

PROMPT [14/14] Table 12: SIMULATIONS (What-If Attack Runs)
CREATE TABLE SIMULATIONS (
    SIMULATION_ID VARCHAR2(50) PRIMARY KEY,
    SIMULATION_NAME VARCHAR2(150) NOT NULL,
    ENTRY_POINT VARCHAR2(50) NOT NULL REFERENCES ASSETS(ASSET_ID),
    TARGET_ASSET VARCHAR2(50) NOT NULL REFERENCES ASSETS(ASSET_ID),
    DEFENSE_APPLIED VARCHAR2(200),
    RISK_BEFORE NUMBER(5,2) NOT NULL,
    RISK_AFTER NUMBER(5,2) NOT NULL,
    RISK_REDUCTION_PCT NUMBER(5,2) NOT NULL,
    OUTCOME VARCHAR2(50) NOT NULL,
    SIMULATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

PROMPT [Extra 1] Table 13: SIMULATION_EVENTS
CREATE TABLE SIMULATION_EVENTS (
    EVENT_ID NUMBER PRIMARY KEY,
    SIMULATION_ID VARCHAR2(50) NOT NULL REFERENCES SIMULATIONS(SIMULATION_ID),
    STEP_NUMBER NUMBER NOT NULL,
    TIMESTAMP_OFFSET_MS NUMBER DEFAULT 0,
    CURRENT_ASSET VARCHAR2(50) NOT NULL REFERENCES ASSETS(ASSET_ID),
    NEXT_ASSET VARCHAR2(50) REFERENCES ASSETS(ASSET_ID),
    TECHNIQUE_ID VARCHAR2(30) REFERENCES ATTACK_TECHNIQUES(TECHNIQUE_ID),
    EVENT_TYPE VARCHAR2(50) NOT NULL,
    DETAILS VARCHAR2(500)
);

PROMPT [Extra 2] Table 14: ALERTS (SOC Alert Queue)
CREATE TABLE ALERTS (
    ALERT_ID VARCHAR2(50) PRIMARY KEY,
    TITLE VARCHAR2(200) NOT NULL,
    SEVERITY VARCHAR2(20) NOT NULL,
    ALERT_TYPE VARCHAR2(50) NOT NULL,
    AFFECTED_ASSET_ID VARCHAR2(50) REFERENCES ASSETS(ASSET_ID),
    MESSAGE VARCHAR2(1000) NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'ACTIVE',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Performance Indexes
